import {openVaultStore} from '../vault-store.js';
import {TestVault} from '../vault-service.js';
const output=document.querySelector('#results'),button=document.querySelector('#run');
const password='Public disposable browser fixture';
const assert=(value,message)=>{if(!value)throw new Error(message);};
async function rejects(action,code){try{await action();}catch(error){assert(error.code===code,'Expected '+code+', got '+error.code);return;}throw new Error('Expected rejection: '+code);}
button.addEventListener('click',async()=>{
  button.disabled=true;output.textContent='Running…\n';
  const stores=[],sessions=[],names=[];
  const open=async(name)=>{const store=await openVaultStore(name);stores.push(store);return store;};
  const session=store=>{const vault=new TestVault(store);sessions.push(vault);return vault;};
  const report=text=>{output.textContent+='PASS '+text+'\n';};
  try{
    const name='aurven-vault-check-'+crypto.randomUUID();names.push(name);
    const first=await open(name),a=session(first);
    await a.create(password,31337);
    const record=await first.read();assert(record?.cipher?.data,'Ciphertext persisted');
    report('Strict IndexedDB transaction persisted encrypted data');
    await rejects(()=>first.create(record),'EXISTS');
    await rejects(()=>first.compareAndSwap({...record,revision:99},record),'CONFLICT');
    assert((await first.read()).revision===0,'Aborted transaction changed data');
    report('Duplicate create and compare-and-swap abort without changing data');
    a.lock();first.close();
    const reopened=await open(name),b=session(reopened);await b.unlock(password);
    assert(b.details.walletId===record.walletId,'Persistent identity changed');
    report('Close/reopen preserves authenticated data');
    const row={chainId:31337,account:'0x'+'11'.repeat(20),epoch:1,pubSeed:'22'.repeat(16),root:'33'.repeat(16),leaf:0,digest:'44'.repeat(16)};
    const c=session(await open(name));await c.unlock(password);
    let release,entered;
    const gate=new Promise(resolve=>{release=resolve;}),ready=new Promise(resolve=>{entered=resolve;});
    const held=navigator.locks.request(name+':writer',async()=>{entered();await gate;});
    await ready;await rejects(()=>b.reserveLeaf(row),'BUSY');release();await held;
    await b.reserveLeaf(row);await rejects(()=>c.reserveLeaf({...row,digest:'55'.repeat(16)}),'USED');
    report('Real Web Locks reject competing writer; independent session rejects reused leaf');
    const backup=await b.exportBackup(),recoveryName=name+'-restore';names.push(recoveryName);
    const restored=session(await open(recoveryName));await restored.restoreBackup(backup,password);
    assert(restored.details.mode==='recovery-readonly'&&restored.details.reservations===1,'Recovery state wrong');
    await rejects(()=>restored.reserveLeaf({...row,leaf:1}),'RECOVERY');
    report('Imported backup retains journal and permanently blocks reservations');
    b.lock();await rejects(()=>b.exportBackup(),'LOCKED');await b.unlock(password);
    assert(b.details.reservations===1,'Reservation lost');
    report('Lock/unlock retains committed leaf record');
    output.textContent+='ALL 6 CHECKS PASSED\n';
  }catch(error){output.textContent+='FAIL '+(error.code??error.message)+'\n';}
  finally{
    sessions.forEach(vault=>vault.lock());stores.forEach(store=>store.close());
    // Only remove databases generated by this test invocation, never user data.
    await Promise.all(names.map(name=>new Promise(resolve=>{const request=indexedDB.deleteDatabase(name);request.onsuccess=request.onerror=request.onblocked=resolve;})));
    button.disabled=false;
  }
});
