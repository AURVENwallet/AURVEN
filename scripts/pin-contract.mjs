import {readFileSync, writeFileSync} from 'node:fs';
import {keccak256} from '../ui/lib/keccak.js';

const artifact = JSON.parse(readFileSync(new URL('../out/BscTestAccount.sol/BscTestAccount.json', import.meta.url)));
const code = artifact.deployedBytecode.object.replace(/^0x/, '');
const bytes = Uint8Array.from(code.match(/../g), byte => parseInt(byte, 16));
const hash = '0x' + Buffer.from(keccak256(bytes)).toString('hex');
const trial = JSON.parse(readFileSync(new URL('../out/BrowserTransferTrial.sol/BrowserTransferTrial.json', import.meta.url)));
const init = trial.bytecode.object;
const trialHash = '0x' + Buffer.from(keccak256(Buffer.from(init.slice(2),'hex'))).toString('hex');
const setup=JSON.parse(readFileSync(new URL('../out/TestnetVaultSetup.sol/TestnetVaultSetup.json',import.meta.url))).bytecode.object;
const setupHash='0x'+Buffer.from(keccak256(Buffer.from(setup.slice(2),'hex'))).toString('hex');
writeFileSync(new URL('../ui/contract-pin.js', import.meta.url),
  '// Generated by scripts/pin-contract.mjs after forge build.\nexport const accountCodeHash = ' + JSON.stringify(hash) +
  ';\nexport const trialInitHash = ' + JSON.stringify(trialHash) + ';\nexport const vaultSetupHash = '+JSON.stringify(setupHash)+';\n');
writeFileSync(new URL('../ui/assets/vault-setup-init.json',import.meta.url),JSON.stringify(setup)+'\n');
writeFileSync(new URL('../ui/assets/browser-trial-init.json',import.meta.url),JSON.stringify(init)+'\n');
console.log('Pinned compiled BscTestAccount runtime', hash);

