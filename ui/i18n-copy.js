const escape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const phrases = new RegExp(Object.keys(english).sort((a,b)=>b.length-a.length).map(escape).join('|'),'g');
export function translateText(text, language='zh-CN') {
  if(language!=='en' || !/[\u3400-\u9fff。，（）]/.test(text)) return text;
  if(text.trim()==='，')return text.replace('，','.');
  // Numbered path levels are dynamic; the numeric value is kept unchanged.
  return text.replace(/第 (\d+) 层/g,'Level $1').replace(phrases,match=>english[match])
    .replace(/。/g,'.').replace(/（/g,'(').replace(/）/g,')');
}

export function normalizeLanguage(value) { return value==='en'?'en':'zh-CN'; }
